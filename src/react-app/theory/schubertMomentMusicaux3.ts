const STEP_QUARTER_MS = 750; // 80 BPM (Allegro moderato in 2/4)

function parsePianoBarNotation(notation: string): SongNoteEvent[] {
	return notation
		.trim()
		.split(/\s+/)
		.map((item) => {
			const [notesRaw, durRaw] = item.split(":");
			const beats = durRaw ? Number(durRaw) : 0.5;
			if (!Number.isFinite(beats) || beats <= 0) {
				throw new Error(`Invalid Schubert beat duration: ${durRaw}`);
			}
			const parts = notesRaw.split("+").map(parsePitchToMidi);
			const stepDurationMs = Math.max(85, Math.round(beats * STEP_QUARTER_MS));
			const isGrace = beats <= 0.15;
			const durationSec = isGrace
				? 0.14
				: Math.max(0.24, (stepDurationMs / 1000) * 1.15);

			const rhParts = parts.filter((p) => p.midi >= 60);
			const displayParts = rhParts.length > 0 ? rhParts : parts;
			const noteLabel =
				displayParts.length > 2
					? `${displayParts[0].pitchName}–${displayParts[displayParts.length - 1].pitchName}`
					: displayParts.map((p) => p.pitchName).join(" + ");

			return {
				midi: parts.map((p) => p.midi),
				durationSec,
				stepDurationMs,
				noteLabel,
				...(parts.length >= 4 ? { spreadSec: 0.018 } : {}),
			};
		});
}

