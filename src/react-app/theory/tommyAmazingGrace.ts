import { STANDARD_TUNING } from "./guitarFretboard";
import type {
	GuitarSongStop,
	GuitarStopTechnique,
	SongExample,
	SongNoteEvent,
} from "./songExamples";

function stopMidi(
	stringIndex: number,
	fret: number,
	technique: GuitarStopTechnique = "normal",
): number {
	const openMidi = STANDARD_TUNING[stringIndex].openMidi;
	if (technique === "harmonic") {
		if (fret === 12) return openMidi + 12;
		if (fret === 7) return openMidi + 19;
		if (fret === 5) return openMidi + 24;
		// Artificial +12 harp harmonics touched at frets 13..15 (fretted at 1..3)
		return openMidi + fret;
	}
	return openMidi + fret;
}

function gEvent(
	stops: Array<[number, number, GuitarStopTechnique?]>,
	durationSec: number,
	stepDurationMs: number,
	noteLabel: string,
	spreadSec?: number,
): SongNoteEvent {
	const guitarStops: GuitarSongStop[] = stops.map(
		([stringIndex, fret, technique]) => ({
			stringIndex,
			fret,
			...(technique ? { technique } : {}),
		}),
	);
	const midi = stops.map(([stringIndex, fret, technique]) =>
		stopMidi(stringIndex, fret, technique),
	);
	return {
		midi,
		durationSec,
		stepDurationMs,
		noteLabel,
		...(spreadSec !== undefined ? { spreadSec } : {}),
		guitarStops,
	};
}

