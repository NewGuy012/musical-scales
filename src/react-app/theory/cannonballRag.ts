const EIGHTH_MS = 125; // 2/2 Cut time at half = 120 BPM (250ms per quarter, 1000ms per bar)
const QUARTER_MS = EIGHTH_MS * 2;
const DOTTED_QUARTER_MS = EIGHTH_MS * 3;
const HALF_MS = EIGHTH_MS * 4;
const WHOLE_MS = EIGHTH_MS * 8;

const CHROMATIC_SHARP = [
	"C",
	"C♯",
	"D",
	"D♯",
	"E",
	"F",
	"F♯",
	"G",
	"G♯",
	"A",
	"A♯",
	"B",
];

function midiToNoteLabel(midi: number): string {
	return `${CHROMATIC_SHARP[midi % 12]}${Math.floor(midi / 12) - 1}`;
}

function durToMs(dur: string): number {
	switch (dur) {
		case "1":
			return WHOLE_MS;
		case "2":
			return HALF_MS;
		case "4.":
			return DOTTED_QUARTER_MS;
		case "4":
			return QUARTER_MS;
		case "8":
			return EIGHTH_MS;
		default:
			throw new Error(`Unsupported Cannonball Rag duration: "${dur}"`);
	}
}

/**
 * Parses compact guitar TAB bars like "0:0/8 5:7/8~0.42 2:6/8 4:5/8~0.55"
 * into SongNoteEvents with generous sustain and zero lag on simultaneous pinches.
 */
function parseGuitarBar(notation: string): SongNoteEvent[] {
	return notation
		.trim()
		.split(/\s+/)
		.filter(Boolean)
		.map((token) => {
			const slashIdx = token.indexOf("/");
			if (slashIdx === -1) {
				throw new Error(`Missing duration in Cannonball token: "${token}"`);
			}
			const stopPart = token.slice(0, slashIdx);
			const durAndRing = token.slice(slashIdx + 1);
			const tildeIdx = durAndRing.indexOf("~");
			const dur = tildeIdx === -1 ? durAndRing : durAndRing.slice(0, tildeIdx);
			const explicitRing =
				tildeIdx === -1 ? undefined : Number(durAndRing.slice(tildeIdx + 1));
			const stepDurationMs = durToMs(dur);
			const { guitarStops, midi } = parseGuitarStops(stopPart);
			const topMidi = Math.max(...midi);
			const label =
				midi.length >= 3
					? `${midiToNoteLabel(midi[0])} Chord (${midiToNoteLabel(topMidi)})`
					: midi.length === 2
						? `${midiToNoteLabel(midi[0])}+${midiToNoteLabel(midi[1])}`
						: midiToNoteLabel(topMidi);
			const autoRingSec = Math.min(
				Math.max(stepDurationMs * 1.45, stepDurationMs <= 140 ? 250 : 420),
				1400,
			);
			const durationSec = Number(
				(explicitRing ?? autoRingSec / 1000).toFixed(3),
			);
			const event: SongNoteEvent = {
				midi,
				durationSec,
				stepDurationMs,
				noteLabel: label,
				guitarStops,
			};
			// Simultaneous 2-note thumb+finger pinches should hit together without spread lag
			if (midi.length >= 3) {
				event.spreadSec = 0.018;
			}
			return event;
		});
}

