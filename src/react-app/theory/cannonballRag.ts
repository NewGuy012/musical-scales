const EIGHTH_MS = 160; // 4/4 Ragtime at 188 BPM (160ms per eighth note, 1280ms per bar)
const TRIPLET_EIGHTH_A = 106;
const TRIPLET_EIGHTH_B = 107;
const QUARTER_MS = EIGHTH_MS * 2;
const DOTTED_QUARTER_MS = EIGHTH_MS * 3;
const HALF_MS = EIGHTH_MS * 4;
const WHOLE_MS = EIGHTH_MS * 8;

const TECH_MAP: Record<string, GuitarStopTechnique> = {
	h: "harmonic",
	p: "hammer",
	s: "slide",
};

function stopMidi(
	stringIndex: number,
	fret: number,
	technique?: GuitarStopTechnique,
): number {
	const openMidi = STANDARD_TUNING[stringIndex].openMidi;
	if (technique === "harmonic") {
		if (fret === 12) return openMidi + 12;
		if (fret === 7) return openMidi + 19;
		if (fret === 5) return openMidi + 24;
	}
	return openMidi + fret;
}

function durToMs(dur: string, tripletSlot: number): number {
	switch (dur) {
		case "8":
			return EIGHTH_MS;
		case "4":
			return QUARTER_MS;
		case "4.":
			return DOTTED_QUARTER_MS;
		case "2":
			return HALF_MS;
		case "1":
			return WHOLE_MS;
		case "t":
			return tripletSlot === 0 ? TRIPLET_EIGHTH_A : TRIPLET_EIGHTH_B;
		default:
			throw new Error(`Unsupported Cannonball Rag duration "${dur}"`);
	}
}

function parseGuitarBar(notation: string): SongNoteEvent[] {
	let tripletSlot = 0;
	return notation
		.trim()
		.split(/\s+/)
		.map((token) => {
			const slashIdx = token.lastIndexOf("/");
			if (slashIdx === -1) {
				throw new Error(`Missing duration on guitar token "${token}"`);
			}
			const chordExpr = token.slice(0, slashIdx);
			const dur = token.slice(slashIdx + 1);
			const stepDurationMs = durToMs(dur, tripletSlot);
			if (dur === "t") {
				tripletSlot = (tripletSlot + 1) % 3;
			}
			const guitarStops: GuitarSongStop[] = chordExpr.split("+").map((tok) => {
				const [strRaw, rest] = tok.split(":");
				const tech = TECH_MAP[rest.slice(-1)];
				const fret = Number(tech ? rest.slice(0, -1) : rest);
				return {
					stringIndex: Number(strRaw),
					fret,
					...(tech ? { technique: tech } : {}),
				};
			});
			const midi = guitarStops.map((s) =>
				stopMidi(s.stringIndex, s.fret, s.technique),
			);
			const isChord = guitarStops.length > 1;
			const label = guitarStops
				.map((s) => {
					const name = STANDARD_TUNING[s.stringIndex].label;
					const suffix =
						s.technique === "harmonic"
							? "h"
							: s.technique === "slide"
								? "s"
								: s.technique === "hammer"
									? "H"
									: "";
					return `${name}:${s.fret}${suffix}`;
				})
				.join(" ");
			return {
				midi,
				durationSec: Number(
					(Math.max(stepDurationMs * 0.92, 110) / 1000).toFixed(3),
				),
				stepDurationMs,
				noteLabel: label,
				...(isChord ? { spreadSec: 0.025 } : {}),
				guitarStops,
			};
		});
}

